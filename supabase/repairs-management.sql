-- This creates new repair tables only; it does not modify existing product/catalogue data.

create table if not exists public.customers (
  id uuid primary key default gen_random_uuid(),
  full_name text not null,
  phone text not null unique,
  email text,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table if not exists public.repair_jobs (
  id uuid primary key default gen_random_uuid(),
  customer_id uuid not null references public.customers(id) on delete restrict,
  device_type text not null,
  brand text not null,
  model text not null,
  serial_or_imei text,
  reported_issue text not null,
  diagnosis text,
  quoted_amount numeric(12,2) check (quoted_amount is null or quoted_amount >= 0),
  status text not null default 'received'
    check (status in (
      'received',
      'diagnosing',
      'awaiting_customer_approval',
      'awaiting_parts',
      'in_progress',
      'ready_for_collection',
      'collected',
      'cancelled'
    )),
  assigned_technician text,
  internal_notes text,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table if not exists public.repair_status_history (
  id bigint generated by default as identity primary key,
  repair_id uuid not null references public.repair_jobs(id) on delete cascade,
  old_status text,
  new_status text not null,
  notes text,
  changed_at timestamptz not null default now()
);

create index if not exists repair_jobs_customer_id_idx on public.repair_jobs(customer_id);
create index if not exists repair_jobs_status_created_idx on public.repair_jobs(status, created_at desc);
create index if not exists repair_status_history_repair_id_idx on public.repair_status_history(repair_id);

alter table public.customers enable row level security;
alter table public.repair_jobs enable row level security;
alter table public.repair_status_history enable row level security;

drop policy if exists "Admins manage customers" on public.customers;
create policy "Admins manage customers"
  on public.customers for all
  to authenticated
  using ((select public.is_admin()))
  with check ((select public.is_admin()));

drop policy if exists "Admins manage repair jobs" on public.repair_jobs;
create policy "Admins manage repair jobs"
  on public.repair_jobs for all
  to authenticated
  using ((select public.is_admin()))
  with check ((select public.is_admin()));

drop policy if exists "Admins manage repair status history" on public.repair_status_history;
create policy "Admins manage repair status history"
  on public.repair_status_history for all
  to authenticated
  using ((select public.is_admin()))
  with check ((select public.is_admin()));

grant select, insert, update, delete on public.customers to authenticated;
grant select, insert, update, delete on public.repair_jobs to authenticated;
grant select, insert, update, delete on public.repair_status_history to authenticated;
grant usage, select on sequence public.repair_status_history_id_seq to authenticated;
